'use strict';
const fs = require('node:fs');
const path = require('node:path');
const directory = __dirname;
const core = fs.readFileSync(path.join(directory, 'core.js'), 'utf8');
const source = fs.readFileSync(path.join(directory, 'main.src.js'), 'utf8');
const result = source.replace("require('./core')", `(() => { const module = { exports: {} };\n${core}\nreturn module.exports; })()`);
if (result === source) throw new Error('The core import was not found; refusing to emit an incomplete plugin.');
fs.writeFileSync(path.join(directory, 'main.js'), '// Generated by build.js. Edit main.src.js and core.js.\n' + result);
console.log('Built PDF location bookmarks main.js');
